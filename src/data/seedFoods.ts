import type {
  Food,
  FoodBasis,
  FoodCategory,
  LocalizedText,
} from '../domain/types';

export const SEED_VERSION = 1;
const SEED_TIMESTAMP = '2025-01-01T00:00:00.000Z';

interface SeedFoodInput {
  id: string;
  names: LocalizedText;
  category: FoodCategory;
  basis: FoodBasis;
  kcal: number;
  proteinG: number;
  carbsG: number;
  fatG: number;
  servings?: { label: string; grams: number }[];
}

function makeSeedFood(input: SeedFoodInput): Food {
  return {
    id: `builtin-${input.id}`,
    names: input.names,
    category: input.category,
    basis: input.basis,
    nutritionPer100g: {
      kcal: input.kcal,
      proteinG: input.proteinG,
      carbsG: input.carbsG,
      fatG: input.fatG,
    },
    servings: (input.servings ?? []).map((serving, index) => ({
      id: `builtin-${input.id}-serving-${index + 1}`,
      label: serving.label,
      grams: serving.grams,
    })),
    source: 'builtin',
    createdAt: SEED_TIMESTAMP,
    updatedAt: SEED_TIMESTAMP,
  };
}

